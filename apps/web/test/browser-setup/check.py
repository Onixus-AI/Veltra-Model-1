"""Exercise the real setup component against an isolated preference-store fixture."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

out = Path('work/setup-screenshots')
out.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1280, 'height': 1000})
    page.goto('http://127.0.0.1:3189/')
    page.get_by_role('combobox', name='Start with', exact=True).select_option('business')
    page.get_by_role('textbox', name='What should Veltra help you accomplish?', exact=True).fill('Organize follow-ups')
    page.get_by_role('combobox', name='Timezone', exact=True).fill('America/New_York')
    page.get_by_role('checkbox', name='Use this timezone for my date and time answers.').check()
    page.get_by_role('button', name='Save and continue', exact=True).click()
    expect(page.get_by_role('heading', name='Connect only what your first task needs.')).to_be_visible()
    page.get_by_role('button', name='Open Mail', exact=True).click()
    expect(page.locator('[aria-label="Opened tool"]')).to_have_text('mail')
    page.get_by_role('button', name='Save for later', exact=True).click()
    page.reload()
    expect(page.get_by_role('heading', name='Connect only what your first task needs.')).to_be_visible()
    page.get_by_role('button', name='Continue to first task', exact=True).click()
    expect(page.get_by_role('button', name='Save setup and open task', exact=True)).to_be_disabled()
    page.goto('http://127.0.0.1:3189/?business-ready')
    page.get_by_role('button', name='Save setup and open task', exact=True).click()
    expect(page.get_by_role('textbox', name='Prepared task', exact=True)).to_have_value('Find customers who need a follow-up and prepare drafts.')
    expect(page.get_by_role('status')).to_contain_text('Review the request in Chat')
    page.screenshot(path=str(out / 'setup-complete.png'))
    page.goto('http://127.0.0.1:3189/?fail')
    page.get_by_role('button', name='Edit setup', exact=True).click()
    page.get_by_role('textbox', name='What should Veltra help you accomplish?', exact=True).fill('Unsaved change')
    page.get_by_role('button', name='Save and continue', exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('not saved')
    expect(page.locator('[aria-label="Saved goal"]')).to_have_text('Organize follow-ups')
    page.screenshot(path=str(out / 'setup-save-failure.png'))
    for mode, heading in [('personal', 'Plan my day'), ('dev', 'Plan a development task'), ('creator', 'Create a content brief')]:
        context = browser.new_context(viewport={'width': 390, 'height': 844})
        mobile = context.new_page()
        mobile.goto('http://127.0.0.1:3189/')
        mobile.get_by_role('combobox', name='Start with', exact=True).select_option(mode)
        mobile.get_by_role('textbox', name='What should Veltra help you accomplish?', exact=True).fill('Help with my first project')
        mobile.get_by_role('combobox', name='Timezone', exact=True).fill('Asia/Tokyo')
        mobile.get_by_role('checkbox', name='Use this timezone for my date and time answers.').check()
        mobile.get_by_role('button', name='Save and continue', exact=True).click()
        mobile.get_by_role('button', name='Continue to first task', exact=True).click()
        expect(mobile.get_by_role('heading', name=heading, exact=True)).to_be_visible()
        mobile.screenshot(path=str(out / f'setup-{mode}-mobile.png'))
        mobile.get_by_role('button', name='Save setup and open task', exact=True).click()
        expect(mobile.get_by_role('textbox', name='Prepared task', exact=True)).not_to_have_value('')
        context.close()
    browser.close()
