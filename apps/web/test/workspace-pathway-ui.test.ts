import test from 'node:test';
import assert from 'node:assert/strict';
import {dom} from './helpers/dom-global';
import './helpers/react-global';
import {act,createElement,Fragment} from 'react';
import {useWorkspaceBusiness} from '../lib/workspace-business';
import {createRoot} from 'react-dom/client';
import {browserSupabase} from '../lib/supabase';
import {workspaceSettingsService} from '../lib/workspace-settings-client';
import {defaultSettings} from '../lib/workspace-settings';
import Provider from '../components/workspace-settings-provider';
import Pathway from '../components/workspace-pathway';
function deferred<T>(){let resolve!:(v:T)=>void,reject!:(e:Error)=>void;const promise=new Promise<T>((a,b)=>{resolve=a;reject=b;});return {promise,resolve,reject};}
test('pathways wait for authorized businesses, retain context, reset on account changes and retry failures',async t=>{
 dom.reconfigure({url:'https://workspace.test/workspace/build?workspace=a'});
 const storage=new Map<string,string>();Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(k:string)=>storage.get(k)??null,setItem:(k:string,v:string)=>storage.set(k,v),removeItem:(k:string)=>storage.delete(k)}});
 Object.assign(globalThis,{CustomEvent:dom.window.CustomEvent,self:dom.window});
 process.env.NEXT_PUBLIC_SUPABASE_URL='https://pathway-test.supabase.co';process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY='fixture-public';
 const client=browserSupabase()!;let current='alice',listener:Function=()=>{};
 t.mock.method(client.auth,'getSession',async()=>({data:{session:{user:{id:current}}},error:null}));
 t.mock.method(client.auth,'onAuthStateChange',(fn:Function)=>{listener=fn;return {data:{subscription:{unsubscribe(){}}}};});
 t.mock.method(workspaceSettingsService,'load',async()=>({...defaultSettings(),userId:current,hasLayout:false,hasAppearance:false}));
 let response=deferred<Response>();let calls=0;
 t.mock.method(globalThis,'fetch',async(input:unknown)=>{assert.equal(input,'/api/crm/workspaces');calls++;return response.promise;});
 const host=document.body.appendChild(document.createElement('div')),root=createRoot(host);
 t.after(()=>{act(()=>root.unmount());host.remove();void client.auth.stopAutoRefresh();});
 function BusinessContext(){const business=useWorkspaceBusiness();return createElement('span',{'data-test-business':business});}
 const render=(pathway:'build'|'growth')=>root.render(createElement(Provider,null,createElement(Fragment,null,createElement(BusinessContext),createElement(Pathway,{pathway}))));
 await act(async()=>render('build'));assert.match(host.textContent!,/Loading your businesses/);assert.equal(host.querySelector('.workspace-pathway-steps'),null);
 await act(async()=>{response.resolve(Response.json({workspaces:[{id:'a',name:'Mechanic'},{id:'b',name:'Repair shop'}]}));});
 assert.equal((host.querySelector('select') as HTMLSelectElement).value,'a');
 assert.equal(host.querySelector('[data-test-business]')!.getAttribute('data-test-business'),'a','account binding preserves explicit URL context in the shared shell');
 for(const link of host.querySelectorAll('.workspace-pathway-steps a'))assert.equal(new URL((link as HTMLAnchorElement).href).searchParams.get('workspace'),'a');
 assert.match(host.querySelector('.workspace-pathway-transition a')!.getAttribute('href')!,/growth\?workspace=a/);
 await act(async()=>render('growth'));
 assert.match(host.querySelector('h1')!.textContent!,/Grow your business/);
 const select=host.querySelector('select') as HTMLSelectElement;
 await act(async()=>{select.value='b';select.dispatchEvent(new dom.window.Event('change',{bubbles:true}));});
 assert.equal(host.querySelector('.workspace-pathway-transition a')!.getAttribute('href'),'/workspace/build?workspace=b');
 response=deferred<Response>();
 await act(async()=>{current='bob';listener('SIGNED_IN',{user:{id:'bob'}});await new Promise(resolve=>setTimeout(resolve,10));});
 assert.equal(host.querySelector('.workspace-pathway-steps'),null,'previous account business actions disappear immediately');
 assert.equal(host.textContent!.includes('Mechanic'),false);
 await act(async()=>{response.reject(Error('offline'));});
 assert.match(host.querySelector('[role=alert]')!.textContent!,/could not load/);
 response=deferred<Response>();
 await act(async()=>{(host.querySelector('[role=alert] button') as HTMLButtonElement).click();});
 await act(async()=>{response.resolve(Response.json({workspaces:[{id:'b',name:'Bob business'}]}));});
 assert.equal((host.querySelector('select') as HTMLSelectElement).value,'','an unrelated URL business is never silently accepted');
 assert.equal(host.querySelector('.workspace-pathway-steps'),null);assert.equal(calls,3);
});
