 await act(async()=>{writes[0].task.resolve({userId:'alice',section:'appearance',value:writes[0].value});await first;});
 assert.equal(writes.length,2);assert.equal(state.appearance.accent,'orange','older receipt cannot undo newer choice');
 await act(async()=>{writes[1].task.reject(Error('Temporarily unavailable'));await second.catch(()=>{});});
 assert.equal(state.pending,false);assert.match(state.error,/Temporarily/);
 let old!:Promise<void>,queued!:Promise<void>;
 await act(async()=>{old=state.saveAppearance({...state.appearance,accent:'red'}).catch(()=>{});queued=state.saveLayout(state.layout).catch(()=>{});});
 await act(async()=>{current='bob';listener('SIGNED_IN',{user:{id:'bob'}});await new Promise(r=>setTimeout(r,10));});
 assert.equal(state.userId,'bob');assert.equal(state.appearance.accent,'cyan');
