 assert.equal(state.userId,'');assert.equal(state.canSave,false);assert.equal(state.appearance.accent,'cyan');
 assert.equal(appearanceButton.disabled,true);assert.equal(host.querySelector('dialog')?.hasAttribute('open'),false);
